"""Regenerate the site's data files from the repository.

    python -m scripts.build_site_data          # write
    python -m scripts.build_site_data --check  # fail if the committed files are stale

Everything the site displays is derived here: the tool list and skill files, the
composed system prompt, the datasets with row counts, and the fitted model contract.

WHY THIS EXISTS. `ui/web/src/data/*.json` is committed, because the front end is a
static build and cannot read the repo at run time. Committed derived data goes
stale silently: someone retrains a model or reruns an arm, the numbers in the repo
move, and the site keeps showing the old ones with no test failing. So the files
are generated by this script and `tests/test_site_data.py` fails when what is
committed no longer matches what this would produce.

WHAT IS HAND-WRITTEN, AND WHY IT IS HERE. The prose blocks below -- the gate rules
and the note about the model's knowledge cutoff -- are editorial, not derived. They
live in this file rather than in the JSON so that the JSON has exactly one author
and can be regenerated without losing anything. Edit them here.

Numbers are never typed in. If a figure appears on the site it was computed from a
file in this repo, and rerunning this script is how it changes.
"""

