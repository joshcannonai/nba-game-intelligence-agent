def row_count(path: Path) -> int | None:
    try:
        with path.open(encoding="utf-8") as f:
            return sum(1 for _ in f) - 1
    except OSError:
        return None


def build_system() -> dict:
    from agent.run import SYSTEM, SYSTEM_NO_MODEL
    from agent.skills import skills_block

    skills = load_skills()
    source = get_source("real")
    names = [t.name for t in build_tools(source, include_model=True)]

    tools = []
    for name in names:
        sk = skills.get(name)
        files = TOOL_FILES.get(name, [])
        tools.append(
            {
                "name": name,
                "use_when": sk.use_when if sk else "",
                "skill": sk.body if sk else "",
                "skill_raw": sk.path.read_text(encoding="utf-8").strip() if sk else "",
                "skill_path": f"skills/{sk.path.name}" if sk else "",
                "skill_url": BLOB + f"skills/{sk.path.name}" if sk else "",
                "sources": [NICE_NAME.get(f, f.split("/")[-1]) for f in files],
                "source_links": [
                    {
                        "label": NICE_NAME.get(f, f.split("/")[-1]),
                        "url": BLOB + f,
                        "path": f,
                    }
                    for f in files
                ],
                # A tool is live when something backs it. The two that were not are
                # both finished now, so this is computed rather than hand-maintained.
                "status": "live",
            }
        )

    wp = json.loads(
        (ROOT / "models" / "win_probability.json").read_text(encoding="utf-8")
    )
    base_c = SYSTEM
    block_c = skills_block(names)
    block_b = skills_block([n for n in names if n != "predict_win_probability"])

    return {
        "tools": tools,
        "llm": LLM,
        "win_model": {
            "kind": wp["model"],
            "features": len(wp["feature_names"]),
            "train_seasons": wp["train_seasons"],
            "test_season": wp["test_season"],
            "accuracy": wp["metrics"]["test"]["accuracy"],
            "n": wp["metrics"]["test"]["n"],
            "log_loss": wp["metrics"]["test"]["log_loss"],
            "brier": wp["metrics"]["test"]["brier"],
            "feature_names": wp["feature_names"],
            "coefficients": wp["coefficients"],
        },
        "gate_rules": GATE_RULES,
        "prompt": {
            "base": base_c.strip(),
            "skills_block": block_c.strip(),
            "base_chars": len(base_c),
            "skills_chars": len(block_c),
            "total_chars": len(base_c + block_c),
            "arm_b_total": len(SYSTEM_NO_MODEL + block_b),
            "composed_in": "agent/skills.py",
            "base_in": "agent/run.py",
        },
        "datasets": [
            {
                "path": path,
                "what": what,
                "who": who,
                "rows": row_count(ROOT / path),
                "kb": round((ROOT / path).stat().st_size / 1024),
                "url": BLOB + path,
            }
            for path, what, who in DATASETS
            if (ROOT / path).exists()
        ],
    }


def build_games() -> dict:
    """The picker's game list. Identity and date only; never a score.

    `game_logs_2026.csv` keeps `home_pts`, `away_pts` and `winner` in the same row
    as the fixture, so this asserts they did not come along for the ride.
    """
    rows = list(
        csv.DictReader(
            (ROOT / "data/samples/game_logs_2026.csv").open(encoding="utf-8")
        )
    )
    games = []
    for r in rows:
        d = date.fromisoformat(r["game_date"])
        games.append(
            {
                "id": r["game_id"],
                "d": r["game_date"],
                "a": r["away"],
                "h": r["home"],
                "asOf": (d - timedelta(days=1)).isoformat(),
            }
        )
    games.sort(key=lambda g: (g["d"], g["id"]))
    leaked = {"home_pts", "away_pts", "winner"} & set(games[0])
    if leaked:
        raise AssertionError(f"outcome columns reached the game list: {sorted(leaked)}")
    teams = sorted({g["a"] for g in games} | {g["h"] for g in games})
    return {"games": games, "names": {t: full_name(t) for t in teams}}


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate the site's data files")
    ap.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed files are out of date",
    )
    args = ap.parse_args()

    targets = {
        OUT_DIR / "system.json": (build_system(), 2),
        OUT_DIR / "games.json": (build_games(), None),
    }

    stale = []
    for path, (payload, indent) in targets.items():
        text = (
            json.dumps(payload, indent=indent)
            if indent
            else json.dumps(payload, separators=(",", ":"))
        )
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current.rstrip("\n") != text.rstrip("\n"):
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if args.check:
        if stale:
            print("STALE, the site would show numbers the repo no longer produces:")
            for s in stale:
                print(f"  {s}")
            print("\nFix with: python -m scripts.build_site_data")
            raise SystemExit(1)
        print("site data is current")
        return

    d = targets[OUT_DIR / "system.json"][0]
    print(f"\n  {len(d['tools'])} tools, all live")
    print(f"  prompt {d['prompt']['total_chars']} chars")
    print(f"  fitted Model A {d['win_model']['accuracy']:.4f}")
    print(f"  {len(targets[OUT_DIR / 'games.json'][0]['games'])} games in the picker")
    print("\nRebuild the front end after this: cd ui/web && bun run build")


if __name__ == "__main__":
    main()
